import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const server = await readFile(path.join(root, 'bridge/src/server.mjs'), 'utf8');
const compose = await readFile(path.join(root, 'bridge/compose.truenas.yml'), 'utf8');
const image = await readFile(path.join(root, 'bridge/Dockerfile.agents'), 'utf8');
const entrypoint = await readFile(path.join(root, 'bridge/agents-entrypoint.sh'), 'utf8');
const sample = JSON.parse(await readFile(path.join(root, 'bridge/config.example.json'), 'utf8'));
const nasSample = JSON.parse(await readFile(path.join(root, 'bridge/config.truenas.example.json'), 'utf8'));
const workflow = await readFile(path.resolve(root, '../.github/workflows/build-forgelink.yml'), 'utf8');
test('TrueNAS container pins and verifies the native Linux agents without embedding credentials', () => {
  assert.match(image, /@anthropic-ai\/claude-code@\$\{CLAUDE_VERSION\}/);
  assert.doesNotMatch(image.slice(0, image.indexOf('RUN npm install')), /USER node/);
  assert.match(image.slice(image.indexOf('RUN npm install')), /USER node/);
  assert.match(image, /ANTIGRAVITY_SHA512/);
  assert.match(image, /install -d -m 0750 -o node -g node \/config/);
  assert.match(image, /sha512sum --check --status/);
  assert.doesNotMatch(image, /dangerously|skip.*permission/i);
  assert.match(compose, /user: \"1000:1000\"/);
  assert.match(entrypoint, /gnome-keyring-daemon --unlock/);
  assert.match(compose, /restart: unless-stopped/);
  assert.match(compose, /\$\{FORGELINK_BIND_IP/);
  assert.match(compose, /:8789:8787/);
  assert.match(compose, /FORGELINK_TEMPLATE: truenas/);
  assert.match(compose, /deepai-agent\/data\/bridge\/secret:\/config\/oracle-secret:ro/);
  assert.match(compose, /\.\/deepai-secret:\/config\/deepai-secret:ro/);
  assert.match(compose, /no-new-privileges:true/);
  assert.match(compose, /\/home\/node/);
  assert.doesNotMatch(image, /COPY.*\.env|ARG .*TOKEN=|ARG .*SECRET=/i);
});
test('generic bridge template defaults to disabled agents without permission bypasses', () => {
  for (const agent of Object.values(sample.agents)) assert.equal(agent.enabled, false);
  assert.doesNotMatch(sample.agents.antigravity.args.join(' '), /dangerously|skip.*permission/i);
});
test('TrueNAS-specific template enables the existing DeepAI account and holds both other agents for private sign-in', () => {
  assert.equal(nasSample.agents.deepai.mode, 'oracle');
  assert.equal(nasSample.agents.deepai.secretFile, '/config/oracle-secret');
  assert.match(nasSample.projects[0].instructions, /Never print, copy, expose, or transmit API tokens/);
  assert.match(nasSample.projects[0].instructions, /Do not publish changes or deployments/);
  assert.equal(nasSample.agents.claude.enabled, false);
  assert.equal(nasSample.agents.antigravity.enabled, false);
  assert.equal(nasSample.agents.claude.args.at(-1), 'plan');
  assert.equal(nasSample.agents.antigravity.args.at(-1), 'plan');
});
test('DeepAI service calls only the allowlisted authenticated TrueNAS API', () => {
  assert.match(server, /X-Oracle-Secret/);
  assert.match(server, /endpoint\.hostname === '172\.16\.41\.1'/);
  assert.match(server, /endpoint\.port === '9395'/);
  assert.match(server, /result\.ok !== true/);
  assert.match(server, /agent\.oracleSecret/);
  assert.match(server, /safe = safe\.replaceAll\(agent\.oracleSecret, '\[REDACTED\]'\)/);
  assert.match(compose, /\.\/deepai-secret:\/config\/deepai-secret:ro/);
  assert.match(compose, /\/run\/secrets\/keyring-password:ro/);
  assert.doesNotMatch(compose, /ORACLE_SECRET:/i);
});
test('existing CI artifact and signing behavior remains guarded on the main branch', () => {
  assert.match(workflow, /github\.ref == 'refs\/heads\/main'/);
  assert.match(workflow, /if: \$\{\{ github\.event_name == 'workflow_dispatch' && inputs\.publish/);
  assert.match(compose, /restart: unless-stopped/);
});
