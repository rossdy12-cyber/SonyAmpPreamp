"""Check appearance controls and persistence in the managed mobile web preview."""
from pathlib import Path
from playwright.sync_api import sync_playwright

ROOT=Path(__file__).resolve().parents[1]

def run():
    with sync_playwright() as pw:
        browser=pw.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
        page=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=2)
        page.goto('http://localhost:4300',wait_until='networkidle')
        address=page.get_by_label('Search or enter an address')
        address.fill('https://www.google.com/')
        address.press('Enter')
        page.get_by_label('Settings',exact=True).click()
        page.get_by_label('Gothic website styling').check()
        page.get_by_label('Original appearance for this site').check()
        page.wait_for_function("Object.values(localStorage).some(x=>{try{const d=JSON.parse(x);return d.settings?.gothic && d.settings.originalSites?.includes('www.google.com')}catch{return false}})")
        page.screenshot(path=str(ROOT/'preview-settings.png'))
        page.reload(wait_until='networkidle')
        page.get_by_label('Settings',exact=True).click()
        assert page.get_by_label('Gothic website styling').is_checked()
        assert page.get_by_label('Original appearance for this site').is_checked()
        page.get_by_label('Close panel').click()
        page.get_by_label('Close panel').wait_for(state='hidden')
        page.get_by_label('Toggle private browsing').click()
        page.get_by_text('A moment',exact=False).wait_for()
        address.click()
        address.fill('https://private.example.net/')
        address.press('Enter')
        page.get_by_text('private.example.net',exact=True).wait_for()
        page.get_by_label('Settings',exact=True).click()
        page.get_by_label('Original appearance for this site').check()
        page.get_by_text('Only remembered during private browsing.',exact=False).wait_for()
        page.get_by_label('Close panel').click()
        page.get_by_label('Close panel').wait_for(state='hidden')
        page.get_by_label('Open 2 tabs').click()
        page.get_by_text('Close all private tabs',exact=True).click()
        page.get_by_label('Settings',exact=True).click()
        assert page.get_by_label('Original appearance for this site').is_checked()
        page.get_by_label('Reset site appearance exceptions').click()
        page.get_by_text('Continue',exact=True).click()
        assert not page.get_by_label('Original appearance for this site').is_checked()
        page.wait_for_function("Object.values(localStorage).some(x=>x.includes('\"originalSites\":[]'))")
        assert not page.evaluate("JSON.stringify(localStorage).includes('private.example.net')")
        page.get_by_label('Close panel').click()
        page.get_by_label('Close panel').wait_for(state='hidden')
        page.get_by_label('Toggle private browsing').click()
        page.get_by_text('A moment',exact=False).wait_for()
        address.click()
        address.fill('https://private.example.net/')
        address.press('Enter')
        page.get_by_text('private.example.net',exact=True).wait_for()
        page.get_by_label('Settings',exact=True).click()
        assert not page.get_by_label('Original appearance for this site').is_checked()
        browser.close()
    print('PASS: appearance controls, normal-site persistence, reset confirmation, private-site non-persistence and expiry.')

if __name__=='__main__':
    run()