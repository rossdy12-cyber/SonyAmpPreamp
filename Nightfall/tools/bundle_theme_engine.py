"""Embed the installed MIT-licensed theme engine for offline WebView injection."""
from pathlib import Path
import json
import subprocess

root = Path(__file__).resolve().parents[1]
entry = Path(subprocess.check_output(['node', '-p', "require.resolve('darkreader')"], cwd=root/'packages/mobile', text=True).strip())
license_text = (entry.parent/'LICENSE').read_text()
target = root/'packages/mobile/lib/theme-engine-source.ts'
target.write_text('/* Generated by tools/bundle_theme_engine.py.\n' + license_text + '\n*/\nexport const themeEngineSource = ' + json.dumps(entry.read_text()) + ';\n')
(root/'THIRD-PARTY-NOTICES.md').write_text('# Third-party notices\n\n## Dark Reader\n\nBundled locally for optional website dark styling. https://darkreader.org/\n\n' + license_text)
print(f'Embedded theme engine: {target.stat().st_size} bytes; MIT notice retained.')